"""Write docs/INVENTED.md from the built page: every item the game shows that is not backed by the
OpenStreetMap export or SRTM, with its position(s), why it is there and what would replace it.

    python scripts/invented_doc.py

The categories (with reasons) live in scripts/prep_osm.py (INVENTED); the positions come from the running
game (window.__namche.INV), so the list always matches what is actually placed.
"""
import pathlib, sys, json
from playwright.sync_api import sync_playwright
try: sys.stdout.reconfigure(encoding='utf-8')
except Exception: pass
ROOT = pathlib.Path(__file__).resolve().parents[1]
PAGE = 'file://' + (ROOT / 'build' / 'namche.html').as_posix() + '?test'
with sync_playwright() as pw:
    try: b = pw.chromium.launch(args=['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'])
    except Exception: b = pw.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    pg = b.new_page(); pg.goto(PAGE); pg.wait_for_function('window.__namcheReady===true', timeout=600000)
    D = pg.evaluate('({inv: window.__namche.D.invented, placed: window.__namche.INV, geo: window.__namche.D.geo})')
    b.close()
geo = D['geo']
def ll(x, z): return f"{geo['lat0'] - z / geo['mlat']:.5f}° N, {geo['lon0'] + x / geo['mlon']:.5f}° E"
by = {}
for it in D['placed']: by.setdefault(it['id'], []).append(it)
out = ['# Invented items', '',
       'Everything in the Namche concept that is **not** backed by the OpenStreetMap export',
       '(`data/raw/namche-osm.geojson`) or by SRTM elevation. Generated by `scripts/invented_doc.py` from the',
       'built page, so positions match what the game actually places.', '',
       'Each item carries `invented: true` and a `reason` in `data/data.js` (`NAMCHE.invented`, written by',
       '`scripts/prep_osm.py`). Open the page with `?real` (or set `SHOW_INVENTED = false` in `src/game.js`) to hide',
       'all of them. On the minimap they are marked with a hollow pink diamond.', '',
       'Positions are in the local metre grid (x east, z south; origin 27.8050° N, 86.7100° E) and as latitude/longitude.', '',
       '| Item | id | Placed | Why it is invented | What would replace it |', '| --- | --- | --- | --- | --- |']
for it in D['inv']:
    pts = by.get(it['id'], [])
    if pts:
        where = f"{len(pts)}" + (f" (first at x {pts[0]['x']}, z {pts[0]['z']}; {ll(pts[0]['x'], pts[0]['z'])})" if len(pts) > 1 else f" at x {pts[0]['x']}, z {pts[0]['z']} ({ll(pts[0]['x'], pts[0]['z'])})")
    elif 'x' in it: where = f"seed x {it['x']}, z {it['z']} ({ll(it['x'], it['z'])})"
    else: where = 'rule over the whole town'
    out.append(f"| {it['name']} | `{it['id']}` | {where} | {it['reason']} | {it['replace']} |")
out += ['', '## Every position', '']
for it in D['inv']:
    pts = by.get(it['id'], [])
    if not pts: continue
    out.append(f"**{it['name']}** (`{it['id']}`, {len(pts)}): " + '; '.join(f"({p['x']}, {p['z']})" for p in pts))
    out.append('')
out += ['## Stylised, not invented (kept in `?real`)', '',
        'These belong to mapped features but their look is chosen by rule, not taken from data. They are not hidden by `?real`.', '',
        '- **Buildings**: footprints are OSM; storeys, roof and wall colours, window bays, balconies, shop signs and the door wall are chosen by a seeded rule (storeys from footprint area and kind).',
        '- **Chortens** at OSM shrine and memorial nodes: the positions are OSM (moved up to 14 m to clear buildings and paths); the shape is generic.',
        '- **Gompa** ornaments (gold finials, porch, mural): the building is OSM; the decoration is generic.',
        '- **Stairs and landings**: derived from OSM ways (`highway=steps`, or path stretches steeper than 25° on SRTM); tread and riser layout is computed.',
        '- **Bridges**: placed where an OSM path crosses an OSM stream; the deck and rails are generic.',
        '- **Peaks**: names, heights and summit positions are typed from published survey values in `scripts/prep_osm.py`, not from this OSM export; their ground is SRTM.',
        '']
(ROOT / 'docs' / 'INVENTED.md').write_text('\n'.join(out), encoding='utf-8')
print('wrote docs/INVENTED.md:', len(D['inv']), 'categories,', len(D['placed']), 'placements')
